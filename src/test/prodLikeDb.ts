/**
 * 本番相当のDBを作る。until を渡すと、ファイル名がそれ以下のマイグレーションまでを当てる
 * (段階的な適用を試すとき)。ベースラインは Supabase 固有の内容を含むため BASE で代える。
 */
export async function createProdLikeDb(until = "9"): Promise<PGlite> {
	const db = await PGlite.create();
	await db.exec(BASE + SEED);
	await applyMigrations(db, (file) => file <= until);
	return db;
}

export async function applyMigrations(
	db: PGlite,
	include: (file: string) => boolean,
): Promise<void> {
	await db.exec("reset role");
	for (const file of readdirSync(migrationsUrl).sort()) {
		if (!file.includes("baseline") && include(file)) {
			await db.exec(readFileSync(new URL(file, migrationsUrl), "utf8"));
		}
	}
}

/**
 * 社員 id のアカウントでログインした API クライアントになる。0 はログイン前(anon)。
 * method はログインの方法(JWT の amr)。パスワードなら password、メールの認証コードなら otp。
 */
export async function actAs(db: PGlite, id: number, method = "password"): Promise<void> {
	await db.exec("reset role");
	await db.query(
		"select set_config('request.jwt.claim.sub', $1, false), set_config('request.jwt.claims', $2, false)",
		[
			id ? uid(id) : "",
			id ? JSON.stringify({ amr: [{ method, timestamp: Math.floor(Date.now() / 1000) }] }) : "",
		],
	);
	await db.exec(id ? "set role authenticated" : "set role anon");
}
