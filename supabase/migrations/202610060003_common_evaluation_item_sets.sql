-- Grades that are evaluated on exactly the same items (e.g. 技術1級 and 一般1級) share one
-- item set, instead of each grade owning its own copy of the items.
--   employee_grades.item_set_id          which item set a grade is evaluated on
--   common_evaluation_items.item_set_id  which item set an item belongs to (null: every grade)
-- This replaces common_evaluation_items.grade_id.
begin;

create table if not exists public.common_evaluation_item_sets (
  id smallint generated by default as identity primary key,
  name text not null
);
comment on table public.common_evaluation_item_sets
  is 'A set of common evaluation items. Several grades can point at the same set.';

-- Reference data maintained by the administrator. The app reads only the item_set_id
-- columns, so no policy is added and API roles cannot read or change this table.
alter table public.common_evaluation_item_sets enable row level security;

alter table public.employee_grades
  add column if not exists item_set_id smallint references public.common_evaluation_item_sets (id);
alter table public.common_evaluation_items
  add column if not exists item_set_id smallint references public.common_evaluation_item_sets (id);
create index if not exists common_evaluation_items_item_set_id_idx
  on public.common_evaluation_items (item_set_id);

-- Carry the current assignment over: every grade that owns items gets its own set, named
-- after the grade, so nothing changes until grades are pointed at a shared set.
-- Items without a grade stay common to every grade (item_set_id is null).
do $$
declare
  grade record;
  new_item_set_id smallint;
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'common_evaluation_items'
      and column_name = 'grade_id'
  ) then
    return;
  end if;

  for grade in
    select g.id, g.grade_name
    from public.employee_grades as g
    where g.item_set_id is null
      and exists (select 1 from public.common_evaluation_items as item where item.grade_id = g.id)
    order by g.id
  loop
    insert into public.common_evaluation_item_sets (name)
    values (grade.grade_name)
    returning id into new_item_set_id;

    update public.employee_grades set item_set_id = new_item_set_id where id = grade.id;
    update public.common_evaluation_items set item_set_id = new_item_set_id where grade_id = grade.id;
  end loop;

  alter table public.common_evaluation_items drop column grade_id;
end;
$$;

commit;
